import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { destinationId } from './research-store.mjs';
import { renderHome, renderDestination } from './portal-view.mjs';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const local = path.join(project, 'local');
const docs = path.join(project, 'docs');

function readJson(filename) {
  return JSON.parse(fs.readFileSync(filename, 'utf8'));
}

function writeAtomic(filename, content) {
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  const temporary = `${filename}.${randomUUID()}.tmp`;
  fs.writeFileSync(temporary, content, { flag: 'wx' });
  fs.renameSync(temporary, filename);
}

export function buildPages(workspace = project) {
  const privateDirectory = path.join(workspace, 'local');
  const outputDirectory = path.join(workspace, 'docs');
  const trip = readJson(path.join(privateDirectory, 'trip.json'));
  const catalogFile = path.join(privateDirectory, 'portal/media/catalog.json');
  const catalog = fs.existsSync(catalogFile) ? readJson(catalogFile) : {};
  const marker = path.join(outputDirectory, '.travel-pages-manifest.json');
  const previous = fs.existsSync(marker) ? readJson(marker) : { version: 1, files: [] };
  if (!Array.isArray(previous.files) || previous.files.some(file => !/^(destinations\/[a-f0-9]{16}\.html|media\/[a-z0-9-]+\.(jpg|png|webp)|index\.html|README\.md)$/.test(file))) throw new Error('Invalid generated-pages manifest');
  fs.mkdirSync(outputDirectory, { recursive: true });
  const names = new Set();
  const entries = trip.destinations.map(destination => {
    if (!destination.name?.trim()) throw new Error('Configured destination names are required');
    const id = destinationId(destination);
    if (names.has(id)) throw new Error('Duplicate destination page ID');
    names.add(id);
    return { id, status: 'public-review-required', destination: { name: destination.name }, publicMessage: 'No public-safe assessment has been released. Private research and trip details are not included on this site.' };
  });

  const mediaDirectory = path.join(outputDirectory, 'media');
  fs.mkdirSync(mediaDirectory, { recursive: true });
  const publicMedia = {};
  for (const [name, item] of Object.entries(catalog)) {
    if (!entries.some(entry => entry.destination.name === name) || !/^media\/[a-z0-9-]+\.(jpg|png|webp)$/.test(item.file) || !item.alt?.trim() || !item.credit?.trim() || !/^https:\/\//.test(item.source)) continue;
    const source = path.resolve(privateDirectory, 'portal', item.file);
    if (!source.startsWith(path.resolve(privateDirectory, 'portal') + path.sep) || !fs.existsSync(source) || !fs.realpathSync(source).startsWith(fs.realpathSync(path.join(privateDirectory, 'portal')) + path.sep) || !fs.statSync(source).isFile()) continue;
    const filename = path.basename(item.file);
    const target = path.join(outputDirectory, 'media', filename);
    fs.copyFileSync(source, target);
    publicMedia[name] = { file: `media/${filename}`, alt: item.alt, credit: item.credit };
  }

  const safeTrip = { destinations: trip.destinations.map(({ name }) => ({ name })) };
  const destinationFiles = entries.map(entry => `destinations/${entry.id}.html`);
  const mediaFiles = [...new Set(Object.values(publicMedia).map(item => item.file))];
  const files = [...destinationFiles, ...mediaFiles, 'index.html', 'README.md'].sort();
  for (const entry of entries) writeAtomic(path.join(outputDirectory, 'destinations', `${entry.id}.html`), renderDestination({ ...entry, image: publicMedia[entry.destination.name] }));
  for (const oldFile of previous.files) if (!files.includes(oldFile) && oldFile !== '.travel-pages-manifest.json') fs.rmSync(path.join(outputDirectory, oldFile), { force: true });
  writeAtomic(path.join(outputDirectory, 'index.html'), renderHome(safeTrip, entries.map(entry => ({ ...entry, image: publicMedia[entry.destination.name] }))));
  writeAtomic(path.join(outputDirectory, 'README.md'), '# GitHub Pages build\n\nGenerated by `npm run pages`. Only configured destination names and licensed destination photographs are published. Travelers, dates, budgets, airports, visa and remote-work details, observed prices, booking evidence, reviewer records, private assessments and local state are excluded. Public assessment releases require separate sanitized content and explicit review; none are currently published.\n');
  writeAtomic(marker, `${JSON.stringify({ version: 2, files }, null, 2)}\n`);
  return { pages: entries.length + 1, publicAssessments: 0, privateInputsPublished: false, directory: outputDirectory };
}

export function validateGeneratedPages(workspace = project) {
  const directory = path.join(workspace, 'docs');
  try {
    const manifest = readJson(path.join(directory, '.travel-pages-manifest.json'));
    const privateDirectory = path.join(workspace, 'local');
    const trip = readJson(path.join(privateDirectory, 'trip.json'));
    const catalogFile = path.join(privateDirectory, 'portal/media/catalog.json');
    const catalog = fs.existsSync(catalogFile) ? readJson(catalogFile) : {};
    const expectedFiles = [...trip.destinations.map(destination => `destinations/${destinationId(destination)}.html`), ...Object.entries(catalog).filter(([name, item]) => trip.destinations.some(destination => destination.name === name) && /^media\/[a-z0-9-]+\.(jpg|png|webp)$/.test(item.file) && item.alt?.trim() && item.credit?.trim() && /^https:\/\//.test(item.source)).map(([, item]) => item.file), 'index.html', 'README.md'].sort();
    if (manifest.version !== 2 || !Array.isArray(manifest.files) || new Set(manifest.files).size !== manifest.files.length || JSON.stringify([...manifest.files].sort()) !== JSON.stringify(expectedFiles)) return { valid: false };
    const expected = new Set([...manifest.files, '.travel-pages-manifest.json']);
    const actual = new Set();
    const visit = (current, relative = '') => {
      for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
        const name = relative ? `${relative}/${entry.name}` : entry.name;
        if (entry.isSymbolicLink()) throw new Error('Symlinks are not publishable');
        if (entry.isDirectory()) visit(path.join(current, entry.name), name);
        else if (entry.isFile()) actual.add(name);
        else throw new Error('Unsupported docs entry');
      }
    };
    visit(directory);
    return { valid: actual.size === expected.size && [...actual].every(file => expected.has(file)) };
  } catch { return { valid: false }; }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(buildPages(), null, 2)); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
